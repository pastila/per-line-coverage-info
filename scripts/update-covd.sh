#!/usr/bin/env bash
# Refreshes the covd binaries committed under src/main/resources/bin/ from a coverage-assistant
# build (`make build-covd-all` -> dist/covd) and rewrites the manifest.
#
# Usage: scripts/update-covd.sh [path/to/dist/covd]
# Default: ../raketa/yakov_scripts/coverage/coverage-assistant/dist/covd (sibling checkout)
#
# The binaries are 7-8 MB each (~37 MB per update, history grows by that much): update only when
# covd really changed, in a commit of its own ("Update covd to <version>").
set -euo pipefail

cd "$(dirname "$0")/.."
DIST="${1:-../raketa/yakov_scripts/coverage/coverage-assistant/dist/covd}"
OUT="src/main/resources/bin"

[ -d "$DIST" ] || { echo "update-covd: dist directory not found: $DIST" >&2; exit 2; }

# <dist file>:<resource platform>:<resource name>
PLATFORMS=(
    "covd-linux-amd64:linux-x64:covd"
    "covd-linux-arm64:linux-arm64:covd"
    "covd-darwin-amd64:mac-x64:covd"
    "covd-darwin-arm64:mac-arm64:covd"
    "covd-windows-amd64.exe:win-x64:covd.exe"
)

for entry in "${PLATFORMS[@]}"; do
    IFS=: read -r src _ _ <<<"$entry"
    [ -f "$DIST/$src" ] || { echo "update-covd: missing $DIST/$src (run make build-covd-all)" >&2; exit 2; }
done

if [ -f "$DIST/SHA256SUMS" ]; then
    (cd "$DIST" && sha256sum -c SHA256SUMS >/dev/null) || { echo "update-covd: $DIST/SHA256SUMS does not match the binaries" >&2; exit 2; }
fi

VERSION="unknown"
if [ -x "$DIST/covd-linux-amd64" ]; then
    VERSION="$("$DIST/covd-linux-amd64" --version 2>/dev/null | head -n 1 | tr -d '\r' || true)"
    [ -n "$VERSION" ] || VERSION="unknown"
fi

mkdir -p "$OUT"
MANIFEST="$OUT/covd-manifest.properties"
{
    echo "# Generated by scripts/update-covd.sh; do not edit by hand."
    echo "# <platform>=<sha256 of the binary>; verified by the verifyCovdBinaries task and BundledCovdTest."
    echo "version=$VERSION"
} >"$MANIFEST"

for entry in "${PLATFORMS[@]}"; do
    IFS=: read -r src platform name <<<"$entry"
    mkdir -p "$OUT/$platform"
    cp "$DIST/$src" "$OUT/$platform/$name"
    chmod 755 "$OUT/$platform/$name"
    echo "$platform=$(sha256sum "$OUT/$platform/$name" | cut -d' ' -f1)" >>"$MANIFEST"
done

echo "update-covd: covd $VERSION"
cat "$MANIFEST" | sed -n '3,$p'
echo "update-covd: review with 'git status', then commit as 'Update covd to $VERSION'."
